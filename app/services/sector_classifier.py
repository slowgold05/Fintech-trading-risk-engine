def _clean_company_name(company_name: str) -> str:
    cleaned = company_name.upper()
    cleaned = re.sub(r"\b(COMMON STOCK|ORDINARY SHARES|CLASS [A-Z]|CL [A-Z]|INC\.?|CORP\.?|CORPORATION|COMPANY|LTD\.?|PLC|N\.V\.|S\.A\.)\b", " ", cleaned)
    return re.sub(r"\s+", " ", cleaned).strip()


def infer_sector(symbol: str, company_name: str | None, existing_sector: str | None = None) -> str | None:
    normalized_symbol = symbol.upper().replace("-", ".").strip()
    if normalized_symbol in SECTOR_BY_SYMBOL:
        return SECTOR_BY_SYMBOL[normalized_symbol]

    if existing_sector and existing_sector != "Other":
        return existing_sector

    name = _clean_company_name(company_name or "")
    for sector, pattern in KEYWORD_SECTORS:
        if re.search(pattern, name):
            return sector

    return existing_sector
